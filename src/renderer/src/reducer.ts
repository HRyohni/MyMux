/** Agent calls whose transcript is not loaded yet, with the agent id their result reports. */
export function unloadedAgents(items: ChatItem[]): { toolId: string; agentId: string }[] {
  const out: { toolId: string; agentId: string }[] = []
  for (const b of toolBlocks(items, true)) {
    if ((b.name !== 'Agent' && b.name !== 'Task') || b.sub?.length) continue
    const agentId = /agentId:\s*([\w-]+)/.exec(b.result?.text ?? '')?.[1]
    if (agentId) out.push({ toolId: b.id, agentId })
  }
  return out
}

/** Puts a stored subagent transcript under the Agent call that produced it. */
export function withSubagent(items: ChatItem[], toolId: string, msgs: { type: string; uuid?: string; message: unknown }[]): ChatItem[] {
  let sub: ChatItem[] = []
  for (const m of msgs) {
    if (m.type === 'system') continue
    sub = reduce(sub, { type: m.type, uuid: m.uuid, message: m.message, parent_tool_use_id: null } as unknown as SDKMessage)
  }
  return sub.length ? updateTool(items, toolId, (b) => ({ ...b, sub: sub.slice(-SUB_LIMIT) })) : items
}


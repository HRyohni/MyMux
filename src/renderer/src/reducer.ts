// Pure reduction of SDK messages into chat items. No store or DOM access, so it is unit-testable.
import type { SDKMessage } from '../../shared/ipc'
import { diffStats } from './diff'

export type ToolResult = { text: string; isError: boolean }

export type Block =
  | { type: 'text'; text: string }
  | { type: 'thinking'; text: string }
  | {
    type: 'tool_use'; id: string; name: string; input: unknown; inputJson: string; result?: ToolResult
    /** Transcript of the subagent this Agent/Task call started. */
    sub?: ChatItem[]
  }

export type ChatItem =
  | { kind: 'user'; id: string; uuid?: string; text: string; images?: string[] }
  | { kind: 'assistant'; id: string; blocks: Block[]; streaming: boolean }
  /** costUsd is this turn's share, totalCostUsd the session's running total. */
  | { kind: 'result'; id: string; costUsd: number; totalCostUsd: number; durationMs: number; turns: number; isError: boolean; text?: string }
  | { kind: 'info'; id: string; text: string; level: 'info' | 'error'; markdown?: boolean }

export type ToolBlock = Extract<Block, { type: 'tool_use' }>

const SUB_LIMIT = 300

let counter = 0
export const nid = () => `i${Date.now().toString(36)}${(counter++).toString(36)}`

export function contentToText(content: unknown): string {
  if (typeof content === 'string') return content
  if (Array.isArray(content)) {
    return content
      .map((c) => {
        if (c && typeof c === 'object' && 'type' in c) {
          const b = c as { type: string; text?: string }
          if (b.type === 'text') return b.text ?? ''
          if (b.type === 'image') return '[slika]'
        }
        return ''
      })
      .join('\n')
  }
  if (content == null) return ''
  try { return JSON.stringify(content, null, 2) } catch { return String(content) }
}

function apiBlocksToBlocks(content: unknown[]): Block[] {
  const out: Block[] = []
  for (const raw of content) {
    const b = raw as { type: string; text?: string; thinking?: string; id?: string; name?: string; input?: unknown }
    if (b.type === 'text') out.push({ type: 'text', text: b.text ?? '' })
    else if (b.type === 'thinking') out.push({ type: 'thinking', text: b.thinking ?? '' })
    else if (b.type === 'tool_use' && b.id) {
      out.push({ type: 'tool_use', id: b.id, name: b.name ?? 'tool', input: b.input, inputJson: JSON.stringify(b.input ?? {}) })
    }
  }
  return out
}

/** Applies `fn` to the tool block with the given id, at any subagent depth. */
export function updateTool(items: ChatItem[], id: string, fn: (b: ToolBlock) => ToolBlock): ChatItem[] {
  let touched = false
  const out = items.map((it) => {
    if (it.kind !== 'assistant') return it
    let hit = false
    const blocks = it.blocks.map((b) => {
      if (b.type !== 'tool_use') return b
      if (b.id === id) { hit = true; return fn(b) }
      if (b.sub) {
        const sub = updateTool(b.sub, id, fn)
        if (sub !== b.sub) { hit = true; return { ...b, sub } }
      }
      return b
    })
    if (hit) touched = true
    return hit ? { ...it, blocks } : it
  })
  return touched ? out : items
}

/**
 * What a prompt stored in the transcript should look like in the chat: slash commands are wrapped
 * in <command-name> tags, and command output or caveats are not something the user typed.
 */
export function displayPrompt(text: string): string | null {
  const t = text.trim()
  if (!t) return null
  const cmd = /<command-name>\s*(\/?[^<\s]+)\s*<\/command-name>/.exec(t)
  if (cmd) {
    const args = /<command-args>([\s\S]*?)<\/command-args>/.exec(t)?.[1]?.trim()
    const name = cmd[1].startsWith('/') ? cmd[1] : `/${cmd[1]}`
    return args ? `${name} ${args}` : name
  }
  if (/^<(local-command-[a-z]+|command-message|system-reminder|task-notification)>/.test(t)) return null
  if (t.startsWith('Caveat: The messages below were generated by the user while running local commands')) return null
  return text
}

export function reduce(items: ChatItem[], msg: SDKMessage): ChatItem[] {
  const last = items[items.length - 1]
  const lastAssistant = last && last.kind === 'assistant' && last.streaming ? last : null

  switch (msg.type) {
    case 'stream_event': {
      if (msg.parent_tool_use_id) return items
      const ev = msg.event as { type: string; index?: number; content_block?: unknown; delta?: unknown }
      if (ev.type === 'message_start') {
        return [...items, { kind: 'assistant', id: nid(), blocks: [], streaming: true }]
      }
      if (!lastAssistant) return items
      const blocks = [...lastAssistant.blocks]
      if (ev.type === 'content_block_start' && ev.content_block) {
        const cb = ev.content_block as { type: string; id?: string; name?: string; text?: string; thinking?: string }
        if (cb.type === 'text') blocks.push({ type: 'text', text: cb.text ?? '' })
        else if (cb.type === 'thinking') blocks.push({ type: 'thinking', text: cb.thinking ?? '' })
        else if (cb.type === 'tool_use') blocks.push({ type: 'tool_use', id: cb.id ?? nid(), name: cb.name ?? 'tool', input: {}, inputJson: '' })
        else return items
      } else if (ev.type === 'content_block_delta' && ev.delta && typeof ev.index === 'number') {
        const d = ev.delta as { type: string; text?: string; thinking?: string; partial_json?: string }
        const b = blocks[ev.index]
        if (!b) return items
        if (d.type === 'text_delta' && b.type === 'text') blocks[ev.index] = { ...b, text: b.text + (d.text ?? '') }
        else if (d.type === 'thinking_delta' && b.type === 'thinking') blocks[ev.index] = { ...b, text: b.text + (d.thinking ?? '') }
        else if (d.type === 'input_json_delta' && b.type === 'tool_use') blocks[ev.index] = { ...b, inputJson: b.inputJson + (d.partial_json ?? '') }
        else return items
      } else if (ev.type === 'content_block_stop' && typeof ev.index === 'number') {
        const b = blocks[ev.index]
        if (b?.type === 'tool_use') {
          let input: unknown = {}
          try { input = b.inputJson ? JSON.parse(b.inputJson) : {} } catch { input = { _raw: b.inputJson } }
          blocks[ev.index] = { ...b, input }
        }
      } else if (ev.type === 'message_stop') {
        return [...items.slice(0, -1), { ...lastAssistant, blocks, streaming: false }]
      } else {
        return items
      }
      return [...items.slice(0, -1), { ...lastAssistant, blocks }]
    }

    case 'assistant': {
      const content = (msg.message as { content: unknown[] }).content ?? []
      if (msg.parent_tool_use_id) {
        // A subagent's message: reduce it into the transcript nested under the Agent call that started it.
        const inner = { ...msg, parent_tool_use_id: null } as SDKMessage
        return updateTool(items, msg.parent_tool_use_id, (b) => ({ ...b, sub: reduce(b.sub ?? [], inner).slice(-SUB_LIMIT) }))
      }
      if (lastAssistant) {
        // While streaming, the SDK emits one `assistant` message per finished block.
        // Stream events already built the blocks; only take authoritative tool inputs from here.
        const incoming = apiBlocksToBlocks(content)
        let touched = false
        const blocks = lastAssistant.blocks.map((b) => {
          if (b.type !== 'tool_use') return b
          const m = incoming.find((x) => x.type === 'tool_use' && x.id === b.id)
          if (!m || m.type !== 'tool_use') return b
          touched = true
          return { ...b, input: m.input, inputJson: m.inputJson }
        })
        return touched ? [...items.slice(0, -1), { ...lastAssistant, blocks }] : items
      }
      // No streaming item (history replay, subagents). The transcript stores one entry per block,
      // so consecutive entries are parts of the same reply.
      const fresh = apiBlocksToBlocks(content)
      if (last && last.kind === 'assistant') return [...items.slice(0, -1), { ...last, blocks: [...last.blocks, ...fresh] }]
      return [...items, { kind: 'assistant', id: nid(), blocks: fresh, streaming: false }]
    }

    case 'user': {
      if (msg.parent_tool_use_id) {
        const inner = { ...msg, parent_tool_use_id: null } as SDKMessage
        // Tool results inside a subagent address blocks of its own transcript; its prompt is appended to it.
        const nested = updateTool(items, msg.parent_tool_use_id, (b) => ({ ...b, sub: reduce(b.sub ?? [], inner).slice(-SUB_LIMIT) }))
        return nested
      }
      const uuid = 'uuid' in msg && typeof msg.uuid === 'string' ? msg.uuid : undefined
      const content = (msg.message as { content: unknown }).content
      // The CLI records an interrupt as a user message; it is a note, not something the user typed.
      if (contentToText(content).trim().startsWith('[Request interrupted by user')) {
        return [...items, { kind: 'info', id: nid(), level: 'info', text: 'Prekinuto.' }]
      }
      if (typeof content === 'string') {
        if ('isSynthetic' in msg && msg.isSynthetic) return items
        const text = displayPrompt(content)
        return text ? [...items, { kind: 'user', id: nid(), uuid, text }] : items
      }
      if (!Array.isArray(content)) return items
      const results = content.filter((c) => c && typeof c === 'object' && (c as { type: string }).type === 'tool_result') as Array<{
        tool_use_id: string; content: unknown; is_error?: boolean
      }>
      if (results.length === 0) {
        if ('isSynthetic' in msg && msg.isSynthetic) return items
        const blocks = content as Array<{ type: string; text?: string; source?: { type?: string; media_type?: string; data?: string } }>
        const raw = blocks.filter((b) => b.type === 'text').map((b) => b.text ?? '').join('\n')
        const images = blocks
          .filter((b) => b.type === 'image' && b.source?.type === 'base64' && b.source.data)
          .map((b) => `data:${b.source!.media_type};base64,${b.source!.data}`)
        const text = displayPrompt(raw) ?? ''
        if (!text && images.length === 0) return items
        return [...items, { kind: 'user', id: nid(), uuid, text, images: images.length ? images : undefined }]
      }
      let out = items
      for (const r of results) {
        out = updateTool(out, r.tool_use_id, (b) => ({ ...b, result: { text: contentToText(r.content), isError: !!r.is_error } }))
      }
      return out
    }

    case 'result': {
      let prevTotal = 0
      for (let i = items.length - 1; i >= 0; i--) {
        const it = items[i]
        if (it.kind === 'result') { prevTotal = it.totalCostUsd; break }
      }
      const total = msg.total_cost_usd ?? 0
      const item: ChatItem = {
        kind: 'result', id: nid(),
        // The SDK reports a running total; a smaller value means the total was reset (/clear).
        costUsd: total >= prevTotal ? total - prevTotal : total,
        totalCostUsd: total, durationMs: msg.duration_ms,
        turns: msg.num_turns, isError: msg.is_error,
        text: msg.is_error ? ('result' in msg ? String(msg.result) : msg.subtype) : undefined,
      }
      const closed = lastAssistant ? [...items.slice(0, -1), { ...lastAssistant, streaming: false }] : items
      return [...closed, item]
    }

    case 'system': {
      if (msg.subtype === 'compact_boundary') {
        const m = msg.compact_metadata
        const k = (n: number) => `${Math.round(n / 1000)}k`
        const size = m.post_tokens ? `${k(m.pre_tokens)} → ${k(m.post_tokens)} tokena` : `${k(m.pre_tokens)} tokena prije sažimanja`
        return [...items, { kind: 'info', id: nid(), level: 'info', text: `Kontekst je sažet (${m.trigger === 'auto' ? 'automatski' : '/compact'}): ${size}` }]
      }
      if (msg.subtype === 'local_command_output') {
        return msg.content.trim() ? [...items, { kind: 'info', id: nid(), level: 'info', text: msg.content, markdown: true }] : items
      }
      const sys = msg as unknown as { subtype: string; hook_name?: string; hook_event?: string; outcome?: string; stderr?: string; output?: string }
      // Hooks run constantly; only the ones that fail are worth a line in the conversation.
      if (sys.subtype === 'hook_response' && sys.outcome === 'error') {
        const detail = (sys.stderr || sys.output || '').trim().slice(0, 600)
        // The headline carries the actual error line, since the rest stays collapsed in the chat.
        const lines = detail.split('\n').map((l) => l.trim()).filter(Boolean)
        const summary = lines.find((l) => /^\w*Error\b/.test(l)) ?? lines[0]
        const name = sys.hook_name ?? ''
        // Names like "PreToolUse:Edit" already say which event fired.
        const event = sys.hook_event && !name.includes(sys.hook_event) ? ` (${sys.hook_event})` : ''
        return [...items, { kind: 'info', id: nid(), level: 'error', text: `Hook ${name}${event} nije uspio${summary ? `: ${summary}${lines.length > 1 ? `\n${detail}` : ''}` : ''}` }]
      }
      if (msg.subtype === 'status' && msg.compact_result === 'failed') {
        return [...items, { kind: 'info', id: nid(), level: 'error', text: `Sažimanje nije uspjelo: ${msg.compact_error ?? 'nepoznata greška'}` }]
      }
      return items
    }

    default: {
      // /clear starts a new conversation: the model no longer sees anything above.
      if ((msg as { type: string }).type === 'conversation_reset') {
        return [{ kind: 'info', id: nid(), level: 'info', text: 'Razgovor je očišćen. Claude više ne vidi prethodne poruke.' }]
      }
      return items
    }
  }
}


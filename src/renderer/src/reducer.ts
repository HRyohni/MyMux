export interface TodoEntry { content: string; status: 'pending' | 'in_progress' | 'completed'; activeForm?: string }

/** Every tool call of the conversation in order, including the ones made by subagents. */
function toolBlocks(items: ChatItem[], deep: boolean): ToolBlock[] {
  const out: ToolBlock[] = []
  for (const it of items) {
    if (it.kind !== 'assistant') continue
    for (const b of it.blocks) {
      if (b.type !== 'tool_use') continue
      out.push(b)
      if (deep && b.sub) out.push(...toolBlocks(b.sub, true))
    }
  }
  return out
}

/** The task list as Claude last left it (TodoWrite, or the TaskCreate/TaskUpdate tools). */
export function latestTodos(items: ChatItem[]): TodoEntry[] {
  let todos: TodoEntry[] = []
  const tasks = new Map<string, TodoEntry>()
  for (const b of toolBlocks(items, false)) {
    const input = (b.input ?? {}) as Record<string, unknown>
    if (b.name === 'TodoWrite' && Array.isArray(input.todos)) {
      todos = (input.todos as TodoEntry[]).filter((t) => t && typeof t.content === 'string')
      tasks.clear()
    } else if (b.name === 'TaskCreate' && typeof input.subject === 'string') {
      const id = /#?(\d+)/.exec(b.result?.text ?? '')?.[1] ?? String(tasks.size + 1)
      tasks.set(id, { content: input.subject, status: 'pending', activeForm: typeof input.activeForm === 'string' ? input.activeForm : undefined })
    } else if (b.name === 'TaskUpdate' && typeof input.taskId === 'string') {
      const cur = tasks.get(input.taskId)
      if (!cur) continue
      if (input.status === 'deleted') tasks.delete(input.taskId)
      else {
        tasks.set(input.taskId, {
          ...cur,
          content: typeof input.subject === 'string' ? input.subject : cur.content,
          status: (input.status as TodoEntry['status'] | undefined) ?? cur.status,
        })
      }
    }
  }
  return tasks.size > 0 ? [...tasks.values()] : todos
}

export interface FileChange { path: string; edits: number; added: number; removed: number; created: boolean }

/** The old/new text pairs of one file-editing tool call. */
export function editsOf(b: ToolBlock): { path: string; pairs: { old: string; new: string }[]; created: boolean } | null {
  const i = (b.input ?? {}) as Record<string, unknown>
  const path = typeof i.file_path === 'string' ? i.file_path : typeof i.notebook_path === 'string' ? i.notebook_path : ''
  if (!path) return null
  const s = (v: unknown) => (typeof v === 'string' ? v : '')
  if (b.name === 'Edit') return { path, pairs: [{ old: s(i.old_string), new: s(i.new_string) }], created: false }
  if (b.name === 'MultiEdit' && Array.isArray(i.edits)) {
    return { path, pairs: (i.edits as Record<string, unknown>[]).map((e) => ({ old: s(e.old_string), new: s(e.new_string) })), created: false }
  }
  if (b.name === 'Write') return { path, pairs: [{ old: '', new: s(i.content) }], created: true }
  if (b.name === 'NotebookEdit') return { path, pairs: [{ old: '', new: s(i.new_source) }], created: false }
  return null
}

/** Files changed by successful Edit/Write calls in this conversation, in order of first change. */
export function changedFiles(items: ChatItem[]): FileChange[] {
  const byPath = new Map<string, FileChange>()
  for (const b of toolBlocks(items, true)) {
    if (!b.result || b.result.isError) continue
    const e = editsOf(b)
    if (!e) continue
    const cur = byPath.get(e.path) ?? { path: e.path, edits: 0, added: 0, removed: 0, created: false }
    for (const p of e.pairs) {
      const st = diffStats(p.old, p.new)
      cur.added += st.added
      cur.removed += st.removed
    }
    cur.edits += 1
    // Only a Write as the first change means the file may be new; a later Write overwrites a known file.
    if (cur.edits === 1) cur.created = e.created
    byPath.set(e.path, cur)
  }
  return [...byPath.values()]
}

export function changedFileCount(items: ChatItem[]): number {
  const paths = new Set<string>()
  for (const b of toolBlocks(items, true)) {
    if (!b.result || b.result.isError) continue
    const e = editsOf(b)
    if (e) paths.add(e.path)
  }
  return paths.size
}
